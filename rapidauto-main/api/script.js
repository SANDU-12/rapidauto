function paymentGateWay() {
    var xhttp = new XMLHttpRequest();
    xhttp.onreadystatechange = function () {
        if (xhttp.readyState === 4) {
            if (xhttp.status === 200) {
                try {
                    var obj = JSON.parse(xhttp.responseText);
                    console.log("Payment data:", obj);

                    // PayHere payment details
                    var payment = {
                        sandbox: true,
                        merchant_id: "1238494",
                        return_url: "http://localhost/rapidauto-full-project/rapidauto-full-project/",
                        cancel_url: "http://localhost/rapidauto-full-project/rapidauto-full-project/",
                        // This must point to your backend notification endpoint
                        notify_url: "http://localhost/rapidauto-full-project/notify.php",
                        order_id: obj.order_id,
                        items: obj.items,
                        amount: obj.amount,
                        currency: obj.currency,
                        // Hash generated by PHP backend
                        hash: obj.hash,
                        first_name: obj.first_name,
                        last_name: obj.last_name,
                        email: obj.email,
                        phone: obj.phone,
                        address: obj.address,
                        city: obj.city,
                        country: "Sri Lanka",
                        delivery_address: "No. 46, Galle Road, Kalutara South",
                        delivery_city: "Kalutara",
                        delivery_country: "Sri Lanka",
                        custom_1: "",
                        custom_2: ""
                    };

                    console.log("Starting PayHere...");
                    payhere.startPayment(payment);
                } catch (error) {
                    console.error("Invalid response from server:", error);
                    alert("Unable to process payment.");
                }
            } else {
                console.error(
                    "Payment request failed. Status:",
                    xhttp.status
                );
                alert("Payment request failed.");
            }
        }
    };
    // Call PHP backend
    xhttp.open("GET", "payhereprocess.php", true);
    xhttp.send();
}
// PayHere success
payhere.onCompleted = function onCompleted(orderId) {
    console.log("Payment completed. Order ID:", orderId);
    alert("Payment successful!\nOrder ID: " + orderId);
};

// PayHere error
payhere.onError = function onError(error) {
    console.error("Payment error:", error);
    alert("Payment failed. Please try again.");
};

// PayHere cancellation
payhere.onDismissed = function onDismissed() {
    console.log("Payment popup dismissed.");
};